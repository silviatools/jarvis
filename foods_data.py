def _build_food(cat, i, item):
    name, kcal, protein, fat, carbs = item[:5]
    food = {
        "id": f"{cat}-{i:03d}",
        "name": name,
        "category": cat,
        "kcal": kcal,
        "protein": protein,
        "fat": fat,
        "carbs": carbs,
    }
    if len(item) > 5:
        food["unitWeight"] = item[5]
    return food


